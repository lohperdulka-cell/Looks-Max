def _direction(metric: MetricScore) -> str:
    """Определяет направление отклонения метрики."""
    if metric.deviation == 0:
        return "balanced"
    if metric.raw_value is None:
        return "too_low"
    return "too_high" if metric.raw_value > metric.reference_value else "too_low"


def _severity(metric: MetricScore) -> str:
    """Степень важности по баллу метрики."""
    if metric.score < 3.0:
        return "high"
    if metric.score < 5.5:
        return "medium"
    return "low"


def build_recommendations(result: ScoreResult, limit: int = 6) -> list[Recommendation]:
    """Собирает приоритизированный список рекомендаций.

    Сортировка: сначала самые низкие баллы (сильнее всего тянут общий результат
    вниз), затем — с учётом веса метрики. Метрика harmony исключается: это
    композит, а не самостоятельная черта.
    """
    candidates: list[Recommendation] = []

    for metric in result.metrics:
        if metric.key == "harmony":
            continue
        spec = METRIC_BY_KEY.get(metric.key)
        if spec is None:
            continue

        direction = _direction(metric)
        severity = _severity(metric)
        if severity == "low":
            continue

        texts = RECOMMENDATION_TEXT.get(metric.key, {})
        entry = texts.get(direction) or texts.get("too_low") or texts.get("too_high")
        if not entry:
            continue

        candidates.append(
            Recommendation(
                key=metric.key,
                label=metric.label,
                category=metric.category,
                priority=0,
                severity=severity,
                direction=direction,
                text=str(entry["text"]),
                actions=[str(a) for a in entry.get("actions", [])],
                source=spec.source,
            )
        )

    # Приоритет: чем ниже балл и чем выше вес метрики, тем важнее.
    def rank(rec: Recommendation) -> tuple[float, float]:
        metric = next(m for m in result.metrics if m.key == rec.key)
        severity_bonus = {"high": 0.0, "medium": 1.0, "low": 2.0}[rec.severity]
        return (metric.score + severity_bonus, -metric.weight)

    candidates.sort(key=rank)
    for index, rec in enumerate(candidates, start=1):
        rec.priority = index
    return candidates[:limit]
