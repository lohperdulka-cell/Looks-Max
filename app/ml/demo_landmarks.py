# Дрожание: парное (симметричное, по x с обратным знаком) плюс мелкая
# независимая добавка, чтобы баллы не выходили «идеально ровными» на любом фото.
_JITTER_SYMMETRIC = 0.0035
_JITTER_ASYMMETRIC = 0.0006


def _mirror_map(points: np.ndarray) -> list[int]:
    """Индекс зеркальной точки для каждой точки (для точек на оси — свой индекс).

    Сравнение идёт по ближайшей зеркальной точке с допуском, а не по строгому
    равенству: шаблон хранится с округлением до 4 знаков, и точного совпадения
    координат при отражении не бывает. Строгое сравнение раньше возвращало
    «каждая точка — своя зеркальная», из-за чего дрожание не было симметричным
    и метрика симметрии получала шум, не связанный с изображением.
    """
    axis = float((points[:, 0].min() + points[:, 0].max()) / 2.0)
    mirrored = np.stack([2.0 * axis - points[:, 0], points[:, 1]], axis=1)
    distances = np.linalg.norm(points[:, None, :] - mirrored[None, :, :], axis=2)
    tolerance = 0.02
    mapping: list[int] = []
    for i in range(len(points)):
        j = int(np.argmin(distances[i]))
        mapping.append(j if distances[i, j] <= tolerance else i)
    return mapping


_BASE = np.asarray(_TEMPLATE, dtype=np.float64)
_MIRROR = _mirror_map(_BASE)


def _seed_from(image_bgr: np.ndarray) -> int:
    """Детерминированный seed по содержимому изображения."""
    digest = hashlib.sha256(np.ascontiguousarray(image_bgr).tobytes()).digest()
    return int.from_bytes(digest[:8], "big")


def synthetic_points(image_bgr: np.ndarray) -> np.ndarray:
    """Возвращает 106 синтетических точек, вписанных в кадр изображения."""
    h, w = image_bgr.shape[:2]
    rng = random.Random(_seed_from(image_bgr))

    points = _BASE.copy()
    jitter = np.zeros_like(points)

    for i in range(len(points)):
        j = _MIRROR[i]
        if i > j:
            continue  # пара уже обработана с меньшим индексом
        dx = rng.uniform(-_JITTER_SYMMETRIC, _JITTER_SYMMETRIC)
        dy = rng.uniform(-_JITTER_SYMMETRIC, _JITTER_SYMMETRIC)
        if i == j:
            dx = 0.0  # точки на оси остаются на оси
        jitter[i] = (dx, dy)
        jitter[j] = (-dx, dy)

    jitter += np.asarray(
        [
            (
                rng.uniform(-_JITTER_ASYMMETRIC, _JITTER_ASYMMETRIC),
                rng.uniform(-_JITTER_ASYMMETRIC, _JITTER_ASYMMETRIC),
            )
            for _ in range(len(points))
        ]
    )
    points += jitter

    # Кадр может быть не квадратным — компенсируем, чтобы лицо не растягивалось.
    if h > 0 and w > 0 and w != h:
        points[:, 0] *= h / w

    return np.clip(points, 0.0, 1.0)


def synthetic_bbox(points: np.ndarray) -> tuple[float, float, float, float]:
    """bbox лица (x1, y1, x2, y2) по синтетическим точкам.

    Верхняя граница поднимается над контуром на долю высоты контура: у реальных
    детекторов (SCRFD) bbox включает лоб, и именно по нему оценивается трихион.
    Доля 0.352 замерена на реальных кадрах (t1 0.35, grace 0.30, astronaut 0.43),
    а не взята «на глаз»: от неё напрямую зависит верхняя треть лица.
    """
    x1 = float(points[:, 0].min())
    y1 = float(points[:, 1].min())
    x2 = float(points[:, 0].max())
    y2 = float(points[:, 1].max())
    face_h = y2 - y1
    return (x1, max(0.0, y1 - FOREHEAD_RATIO * face_h), x2, y2)
